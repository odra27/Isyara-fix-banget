"""matching_logs writer (ADR-038). One parameterized INSERT, metadata only (ADR-012).

created_at is generated by the database. No deduplication (ADR-038 §9).
Database exceptions propagate unchanged; callers decide fail-open vs error.
"""
from __future__ import annotations

from typing import Literal, Protocol
from uuid import UUID

from psycopg import AsyncConnection

Direction = Literal["sign_to_text"]
LoggedAction = Literal["accepted", "confirmed", "escalated_to_jbi"]

_INSERT = (
    "insert into matching_logs (device_id, direction, predicted_phrase_id, confidence, resulted_action) "
    "values (%s, %s, %s, %s, %s)"
)


class MatchingLogWriter(Protocol):
    async def insert(
        self,
        *,
        device_id: UUID,
        direction: Direction,
        predicted_phrase_id: UUID | None,
        confidence: float,
        resulted_action: LoggedAction,
    ) -> None: ...


class PostgresMatchingLogWriter:
    def __init__(self, conn: AsyncConnection) -> None:
        self._conn = conn

    async def insert(
        self,
        *,
        device_id: UUID,
        direction: Direction,
        predicted_phrase_id: UUID | None,
        confidence: float,
        resulted_action: LoggedAction,
    ) -> None:
        async with self._conn.cursor() as cur:
            await cur.execute(_INSERT, (device_id, direction, predicted_phrase_id, confidence, resulted_action))
